class TestExportFilename:
    def test_filename_convention(self, session):
        job = _completed_job_with_results(session, n=1)
        name = export_service.export_filename(job, "xlsx")
        short = job.id.replace("-", "")[:8]
        assert name == f"leadforge_jewelry_stores_{short}.xlsx"
        assert export_service.export_filename(job, "csv").endswith(".csv")

    def test_filename_sanitizes_industry(self, session):
        job = make_job(industry="Jewelry Stores & Repair (CA)!")
        session.add(job)
        session.commit()
        name = export_service.export_filename(job, "xlsx")
        assert name.startswith("leadforge_jewelry_stores_repair_ca_")
        assert all(c.isalnum() or c in "_.-" for c in name)

    def test_filename_rejects_unknown_format(self, session):
        job = make_job()
        session.add(job)
        session.commit()
        with pytest.raises(ValueError):
            export_service.export_filename(job, "pdf")


