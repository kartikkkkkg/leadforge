def _completed_job_with_results(session, n=3, **job_kwargs):
    """A completed job with ``n`` deterministic results (some null fields)."""
    job_kwargs.setdefault("status", "completed")
    job = make_job(**job_kwargs)
    session.add(job)
    session.flush()
    for i in range(n):
        company = make_company(
            company_name=f"Export Test Co {i:02d}",
            normalized_name=f"export test co {i:02d}",
            website=f"https://export{i:02d}.example.com/",
            normalized_domain=f"export{i:02d}.example.com",
            source_url=f"https://export{i:02d}.example.com/",
            city="Los Angeles" if i % 2 == 0 else None,  # null field
            phone=None if i == 0 else f"+1-555-01{i:02d}",  # null field
            public_email=None if i == 1 else f"info@export{i:02d}.example.com",
            linkedin_url=None,  # always null in the demo world
            is_synthetic=(i != 2),  # one non-synthetic row for honesty checks
        )
        session.add(company)
        session.flush()
        result = make_result(
            job,
            company,
            quality_score=95 - i * 10,
            validation_status="valid" if i != 1 else "invalid",
        )
        session.add(result)
    session.commit()
    return job


