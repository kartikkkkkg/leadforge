def _wait_completed(client, job_id, timeout_s=15.0):
    deadline = time.time() + timeout_s
    while time.time() < deadline:
        job = client.get(f"/api/research/jobs/{job_id}").json()
        if job["status"] in ("completed", "failed"):
            return job
        time.sleep(0.05)
    raise TimeoutError(f"job {job_id} did not finish")


class TestExportApi:
    def test_csv_export_download(self, client):
        resp = client.post(
            "/api/research/jobs",
            json={
                "industry": "Jewelry Stores",
                "country": "United States",
                "requested_leads": 10,
                "demo_delay_ms": 0,
            },
        )
        assert resp.status_code == 202
        job_id = resp.json()["id"]
        job = _wait_completed(client, job_id)
        assert job["status"] == "completed"

        resp = client.post(f"/api/research/jobs/{job_id}/export?format=csv")
        assert resp.status_code == 200
        assert resp.headers["content-type"].startswith("text/csv")
        disp = resp.headers["content-disposition"]
        assert disp.startswith("attachment;")
        assert disp.endswith('.csv"')
        assert "leadforge_jewelry_stores_" in disp
        assert resp.content.startswith(b"\xef\xbb\xbf")
        rows = list(csv.DictReader(io.StringIO(resp.content.decode("utf-8-sig"))))
        assert len(rows) == job["accepted"]
        assert list(rows[0].keys()) == list(export_service.EXPORT_COLUMNS)

    def test_xlsx_export_download(self, client):
        resp = client.post(
            "/api/research/jobs",
            json={
                "industry": "Jewelry Stores",
                "country": "United States",
                "requested_leads": 10,
                "demo_delay_ms": 0,
            },
        )
        assert resp.status_code == 202
        job_id = resp.json()["id"]
        job = _wait_completed(client, job_id)
        assert job["status"] == "completed"

        resp = client.post(f"/api/research/jobs/{job_id}/export?format=xlsx")
        assert resp.status_code == 200
        assert (
            resp.headers["content-type"]
            == "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"
        )
        disp = resp.headers["content-disposition"]
        assert disp.startswith("attachment;")
        assert disp.endswith('.xlsx"')
        wb = load_workbook(io.BytesIO(resp.content))
        assert wb.sheetnames == ["Leads", "Research Summary", "Parameters"]
        assert wb["Leads"].max_row - 1 == job["accepted"]

    def test_export_missing_job_404(self, client):
        resp = client.post("/api/research/jobs/does-not-exist/export?format=csv")
        assert resp.status_code == 404
        assert resp.json()["code"] == "job_not_found"

    def test_export_invalid_format_422(self, client):
        resp = client.post(
            "/api/research/jobs",
            json={
                "industry": "Jewelry Stores",
                "country": "United States",
                "requested_leads": 10,
                "demo_delay_ms": 0,
            },
        )
        job_id = resp.json()["id"]
        _wait_completed(client, job_id)
        resp = client.post(f"/api/research/jobs/{job_id}/export?format=pdf")
        assert resp.status_code == 422

    def test_export_non_completed_job_409(self, client, engine):
        # Insert a queued job directly: with TestClient, background tasks run
        # to completion inside the create POST, so a queued job cannot be
        # observed by racing the API.
        with session_scope(engine) as session:
            job = make_job(status="queued", industry="Jewelry Stores")
            session.add(job)
            session.commit()
            job_id = job.id
        resp = client.post(f"/api/research/jobs/{job_id}/export?format=csv")
        assert resp.status_code == 409
        assert resp.json()["code"] == "job_not_runnable"

    def test_export_zero_results(self, client, engine):
        # Completed job with no results: valid empty export.
        with session_scope(engine) as session:
            job = make_job(status="completed", industry="Jewelry Stores")
            session.add(job)
            session.commit()
            job_id = job.id
        resp = client.post(f"/api/research/jobs/{job_id}/export?format=csv")
        assert resp.status_code == 200
        rows = list(csv.reader(io.StringIO(resp.content.decode("utf-8-sig"))))
        assert len(rows) == 1  # header only
        resp = client.post(f"/api/research/jobs/{job_id}/export?format=xlsx")
        assert resp.status_code == 200
        wb = load_workbook(io.BytesIO(resp.content))
        assert wb["Leads"].max_row == 1


