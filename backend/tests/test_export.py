class TestExportCli:
    def test_cli_export_csv_writes_file(self, engine, monkeypatch, tmp_path):
        monkeypatch.setattr("leadforge.db.get_engine", lambda: engine)
        with session_scope(engine) as session:
            job = _completed_job_with_results(session, n=2)
            job_id = job.id
        out = tmp_path / "leads.csv"
        rc = cli_module.main(
            ["export", "--job", job_id, "--format", "csv", "--out", str(out)]
        )
        assert rc == 0
        assert out.exists()
        content = out.read_bytes()
        assert content.startswith(b"\xef\xbb\xbf")
        rows = list(csv.DictReader(io.StringIO(content.decode("utf-8-sig"))))
        assert len(rows) == 2

    def test_cli_export_xlsx_writes_file(self, engine, monkeypatch, tmp_path):
        monkeypatch.setattr("leadforge.db.get_engine", lambda: engine)
        with session_scope(engine) as session:
            job = _completed_job_with_results(session, n=2)
            job_id = job.id
        out = tmp_path / "leads.xlsx"
        rc = cli_module.main(
            ["export", "--job", job_id, "--format", "xlsx", "--out", str(out)]
        )
        assert rc == 0
        wb = load_workbook(out)
        assert wb.sheetnames == ["Leads", "Research Summary", "Parameters"]
        assert wb["Leads"].max_row == 3  # header + 2 rows

    def test_cli_export_missing_job_fails(self, engine, monkeypatch, tmp_path, capsys):
        monkeypatch.setattr("leadforge.db.get_engine", lambda: engine)
        rc = cli_module.main(
            ["export", "--job", "no-such-job", "--out", str(tmp_path / "x.csv")]
        )
        assert rc == 1
        assert "no research job" in capsys.readouterr().out

    def test_cli_export_non_completed_job_fails(
        self, engine, monkeypatch, tmp_path, capsys
    ):
        monkeypatch.setattr("leadforge.db.get_engine", lambda: engine)
        with session_scope(engine) as session:
            job = make_job(status="running")
            session.add(job)
            session.commit()
            job_id = job.id
        rc = cli_module.main(
            ["export", "--job", job_id, "--out", str(tmp_path / "x.csv")]
        )
        assert rc == 1
        assert "only completed jobs" in capsys.readouterr().out
