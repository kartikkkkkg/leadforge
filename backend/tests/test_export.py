class TestExportCsv:
    def test_csv_has_bom_and_expected_headers(self, session):
        job = _completed_job_with_results(session)
        payload = export_service.render_csv(
            export_service.fetch_export_rows(session, job.id)
        )
        assert payload.startswith(b"\xef\xbb\xbf"), "CSV must start with a UTF-8 BOM"
        text = payload.decode("utf-8-sig")
        reader = csv.reader(io.StringIO(text))
        header = next(reader)
        assert header == list(export_service.EXPORT_COLUMNS)
        assert len(header) == 14
        assert "is_synthetic" in header

    def test_csv_rows_match_results(self, session):
        job = _completed_job_with_results(session, n=3)
        rows = export_service.fetch_export_rows(session, job.id)
        payload = export_service.render_csv(rows)
        parsed = list(csv.DictReader(io.StringIO(payload.decode("utf-8-sig"))))
        assert len(parsed) == 3
        assert parsed[0]["company_name"] == "Export Test Co 00"
        assert parsed[0]["quality_score"] == "95"
        assert parsed[0]["is_synthetic"] == "true"
        assert parsed[2]["is_synthetic"] == "false"
        assert parsed[1]["validation_status"] == "invalid"

    def test_csv_null_fields_become_empty(self, session):
        job = _completed_job_with_results(session, n=3)
        rows = export_service.fetch_export_rows(session, job.id)
        parsed = list(
            csv.DictReader(
                io.StringIO(export_service.render_csv(rows).decode("utf-8-sig"))
            )
        )
        assert parsed[0]["phone"] == ""  # null phone -> empty cell
        assert parsed[1]["public_email"] == ""  # null email -> empty cell
        assert parsed[0]["city"] == "Los Angeles"
        assert parsed[1]["city"] == ""  # null city -> empty cell
        # A valid CSV even with nulls: every row has 14 cells.
        for row in parsed:
            assert len(row) == 14

    def test_csv_is_deterministic(self, session):
        job = _completed_job_with_results(session, n=3)
        rows_a = export_service.fetch_export_rows(session, job.id)
        rows_b = export_service.fetch_export_rows(session, job.id)
        assert export_service.render_csv(rows_a) == export_service.render_csv(rows_b)

    def test_csv_zero_results_is_header_only(self, session):
        job = make_job(status="completed")
        session.add(job)
        session.commit()
        rows = export_service.fetch_export_rows(session, job.id)
        assert rows == []
        parsed = list(
            csv.reader(
                io.StringIO(export_service.render_csv(rows).decode("utf-8-sig"))
            )
        )
        assert len(parsed) == 1  # header only, still valid CSV
        assert parsed[0] == list(export_service.EXPORT_COLUMNS)


