class TestExportXlsx:
    def _workbook(self, session, job):
        rows = export_service.fetch_export_rows(session, job.id)
        payload = export_service.render_xlsx(job, rows)
        return load_workbook(io.BytesIO(payload)), rows

    def test_xlsx_has_exactly_three_sheets(self, session):
        job = _completed_job_with_results(session)
        wb, _ = self._workbook(session, job)
        assert wb.sheetnames == ["Leads", "Research Summary", "Parameters"]

    def test_xlsx_leads_headers_and_data(self, session):
        job = _completed_job_with_results(session, n=3)
        wb, _ = self._workbook(session, job)
        ws = wb["Leads"]
        headers = [c.value for c in ws[1]]
        assert headers == list(export_service.XLSX_LEADS_COLUMNS)
        assert "is_synthetic" in headers
        # Data rows: company names, numeric scores, synthetic flags.
        names = [ws.cell(row=r, column=1).value for r in range(2, 5)]
        assert names == ["Export Test Co 00", "Export Test Co 01", "Export Test Co 02"]
        score_col = headers.index("quality_score") + 1
        scores = [ws.cell(row=r, column=score_col).value for r in range(2, 5)]
        assert scores == [95, 85, 75]
        assert all(isinstance(s, int) for s in scores), "score must be a number"
        synth_col = headers.index("is_synthetic") + 1
        assert [ws.cell(row=r, column=synth_col).value for r in range(2, 5)] == [
            True,
            True,
            False,
        ]
        band_col = headers.index("score_band") + 1
        assert [ws.cell(row=r, column=band_col).value for r in range(2, 5)] == [
            "High",
            "Medium",
            "Medium",
        ]

    def test_xlsx_source_url_is_hyperlink_and_date_formatted(self, session):
        job = _completed_job_with_results(session, n=2)
        wb, _ = self._workbook(session, job)
        ws = wb["Leads"]
        headers = [c.value for c in ws[1]]
        url_col = headers.index("source_url") + 1
        date_col = headers.index("collected_at") + 1
        url_cell = ws.cell(row=2, column=url_col)
        assert url_cell.hyperlink is not None
        assert url_cell.hyperlink.target == "https://export00.example.com/"
        date_cell = ws.cell(row=2, column=date_col)
        assert isinstance(date_cell.value, datetime)
        assert date_cell.number_format == "yyyy-mm-dd hh:mm:ss"

    def test_xlsx_styling_freeze_and_filter(self, session):
        job = _completed_job_with_results(session, n=2)
        wb, _ = self._workbook(session, job)
        ws = wb["Leads"]
        header = ws["A1"]
        assert header.font.bold is True
        assert header.fill.start_color.rgb.endswith("E5E7EB")
        assert header.border.bottom.style == "thin"
        assert ws.freeze_panes == "A2"
        assert ws.auto_filter.ref is not None
        # Parameters sheet carries the exact job inputs.
        params = wb["Parameters"]
        param_names = [params.cell(row=r, column=1).value for r in range(2, 11)]
        assert param_names == [
            "industry",
            "country",
            "region",
            "city",
            "keywords",
            "requested_leads",
            "provider",
            "enable_ai",
            "demo_delay_ms",
        ]
        assert params.cell(row=2, column=2).value == "Jewelry Stores"

    def test_xlsx_summary_sheet_totals(self, session):
        job = _completed_job_with_results(session, n=3)
        job.discovered = 10
        job.accepted = 3
        job.duplicates = 4
        job.invalid = 3
        session.commit()
        wb, _ = self._workbook(session, job)
        ws = wb["Research Summary"]
        summary = {
            ws.cell(row=r, column=1).value: ws.cell(row=r, column=2).value
            for r in range(3, ws.max_row + 1)
        }
        assert summary["Discovered"] == 10
        assert summary["Accepted"] == 3
        assert summary["Duplicates removed"] == 4
        assert summary["Invalid"] == 3
        assert summary["Average completeness"] == 85.0
        assert summary["Industry"] == "Jewelry Stores"

    def test_xlsx_leads_sheet_is_deterministic(self, session):
        job = _completed_job_with_results(session, n=2)
        rows = export_service.fetch_export_rows(session, job.id)
        first = export_service.render_xlsx(job, rows)
        second = export_service.render_xlsx(job, rows)
        # The summary sheet embeds an "Exported at" timestamp, so compare the
        # Leads sheet (the deterministic payload) rather than raw bytes.
        sheet1 = load_workbook(io.BytesIO(first))["Leads"]
        sheet2 = load_workbook(io.BytesIO(second))["Leads"]
        assert sheet1.dimensions == sheet2.dimensions
        assert [r for r in sheet1.iter_rows(values_only=True)] == [
            r for r in sheet2.iter_rows(values_only=True)
        ]

    def test_xlsx_zero_results_opens(self, session):
        job = make_job(status="completed")
        session.add(job)
        session.commit()
        wb, _ = self._workbook(session, job)
        assert wb.sheetnames == ["Leads", "Research Summary", "Parameters"]
        assert wb["Leads"].max_row == 1  # header only


